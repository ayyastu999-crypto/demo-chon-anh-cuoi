// Chép chữ: link LAN là http nên navigator.clipboard có thể không có → dùng ô ẩn làm đường lùi
async function chepChu(text) {
  try { await navigator.clipboard.writeText(text); return true; } catch { /* rơi xuống đường lùi */ }
  const t = document.createElement('textarea');
  t.value = text; t.setAttribute('readonly', ''); t.style.position = 'fixed'; t.style.opacity = '0';
  document.body.appendChild(t); t.select();
  const ok = document.execCommand('copy'); t.remove();
  return ok;
}

